const LITE_OFF = { ao: false, dof: "off", bloom: "off", shadowSoft: false, aa: "off" };
export function exportSettings(q, settings, previewSs = 1) {
  if (!q || q === "standard" || !EXPORT_QUALITIES.some((x) => x.id === q)) return null;
  const s = settings && typeof settings === "object" ? settings : {},
    g = { ...(s.graphics || {}) };
  const smallShadows = () => {
    g.shadowSize = Math.min(1024, g.shadowSize ?? 1024);
  };
  if (q === "draft") {
    Object.assign(g, LITE_OFF, { exportSs: 1, exportSamples: 1 });
    smallShadows();
    delete g.lite;
  } else if (q === "max") Object.assign(g, { exportSs: 3, aa: "msaa8", shadowSize: 4096, exportBitrate: "max" });
  else {
    const lite = !!g.lite,
      scale = typeof g.scale === "number" ? g.scale : 1;
    if (lite) {
      Object.assign(g, LITE_OFF);
      smallShadows();
    }
    g.exportSs = Math.max(0.25, Math.round(previewSs * scale * 100) / 100);
    g.exportSamples = 1;
    delete g.lite;
    delete g.scale;
    delete g.maxFps;
  }
  return { ...s, graphics: g };
}
function checkOne(c, v) {
  if (v === null) return c.def === null ? null : `${c.label}: needs a value.`;
  if (c.type === "toggle") return typeof v === "boolean" ? null : `${c.label} must be on or off.`;
  if (c.type === "select") return c.options.some((o) => o.value === v) ? null : `${c.label}: "${String(v)}" is not one of its choices.`;
  if (typeof v !== "number" || !isFinite(v)) return `${c.label} must be a number.`;
  if (v < c.min - 1e-9 || v > c.max + 1e-9) return `${c.label} must be between ${c.min} and ${c.max}.`;
  return null;
}
export function validateGraphics(g) {
  if (g === void 0) return null;
  if (!g || typeof g !== "object" || Array.isArray(g)) return "Graphics settings must be an object.";
  for (const [k, v] of Object.entries(g)) {
    const c = GFX_BY_KEY[k];
    if (!c) return `Unknown graphics setting "${k}".`;
    const e = checkOne(c, v);
    if (e) return e;
  }
  return null;
}
export function compactGraphics(g) {
  const o = {};
  for (const [k, v] of Object.entries(g || {})) {
    const c = GFX_BY_KEY[k];
    if (c && v !== void 0 && v !== null && v !== c.def) o[k] = v;
  }
  return o;
}
