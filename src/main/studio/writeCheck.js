import path from "node:path";
import { insideDir } from "../agent/sessions";

const rx = (glob) =>
  new RegExp(
    "^" +
      glob
        .replace(/[.+^${}()|[\]\\]/g, "\\$&")
        .replace(/\*\*/g, "\0")
        .replace(/\*/g, "[^/]*")
        .replace(/\u0000/g, ".*") +
      "$",
    "i",
  );
const ALWAYS = [
  ["project.json", "project.json is the app's (the stage, the views and the look are set through the studio tools)"],
  ["CLAUDE.md", "CLAUDE.md is regenerated by the app"],
  ["STYLE.md", "STYLE.md holds the user's own rules (Memory)"],
  [".suite/**", ".suite/ is the app's (issues, versions, frames)"],
  [".claude/**", ".claude/ holds the skills and Studio docs the app installs"],
  [".git/**", "the history is the app's"],
  [".style-pkg/**", "the carried package is the app's"],
  [".custom-style/**", "the carried style is the app's"],
  ["qa/mustfail/**", "the must-fail proofs are what the checks are trusted by"],
  ["scenes/mustfail_*.js", "the must-fail scenes are what the checks are trusted by: fix the style, never the proof"],
  ["lib/contact.js", "lib/contact.js is a sign-off check: fix the scene so it passes, never the check"],
  ["lib/collide.js", "lib/collide.js is a sign-off check: fix the scene so it passes, never the check"],
  ["lib/check.js", "lib/check.js is the low poly engine's layout / clipping check: fix the scene so it passes, never the check"],
  ["lib/scan.js", "lib/scan.js is the low poly asset scan the app itself runs (credits): it stays the app's"],
  ["vendor/**", "vendor/ is three.js itself"],
  ["fonts/**", "fonts come only from the font library (add_font)"],
  ["skill/PITFALLS.md", "skill/PITFALLS.md is written by the app from the lessons of fixed issues"],
  [
    "library/**",
    "library/ holds Library entries the app copied in (library_use): import them, never edit them in place (a change becomes your own file in lib/ or scenes/)",
  ],
];
const REFERENCE_OK = "reference/ANALYSIS.md";
const AUDIO_ALLOWED = [];
const ENGINE = ["engine.js", "models.js", "lib/**"];
const TEXT = ["skill/STYLE_GUIDE.md", "skill/QUALITY.md", "style.json"];
const STYLE_ALLOW = {
  brief: [],
  study: [REFERENCE_OK],
  guide: [...TEXT, "scenes/hero*.js", ...ENGINE],
  kit: [...TEXT, "scenes/kit*.js", ...ENGINE],
  sample: [...TEXT, "scenes/sample*.js", "scenes/kit*.js", ...ENGINE],
  review: [...TEXT, "scenes/hero*.js", "scenes/kit*.js", "scenes/sample*.js", ...ENGINE],
  publish: [...TEXT],
};
const LOOK_ALLOW = {
  brief: [],
  study: [REFERENCE_OK],
  look: ["skill/LOOK.md", "skill/QUALITY.md"],
  review: ["skill/LOOK.md", "skill/QUALITY.md"],
  save: [],
};
export function allowedFor(studio, stage) {
  return ((studio.mode === "look" ? LOOK_ALLOW : STYLE_ALLOW)[stage] ?? []).slice();
}
export function libraryUseCheck(studio) {
  const allow = allowedFor(studio, studio.stage);
  if (allow.some((g) => /^scenes\//.test(g) || g === "lib/**")) return null;
  return `Not at the ${studio.stage} stage: Library entries are copied in only at the stages that write scenes or lib/ (${studio.mode === "look" ? "a look never changes code" : "guide, kit, sample, review"}). Read them with library_get meanwhile.`;
}
export function studioWriteCheck(dir, studio, target) {
  if (!target) return "No file was named.";
  if (!insideDir(dir, target)) return `The Style Studio only writes inside this workspace (${dir}).`;
  const rel = path.relative(path.resolve(dir), path.resolve(dir, target)).split(path.sep).join("/");
  if (!rel || rel.startsWith("..")) return "That is the workspace folder itself, not a file in it.";
  const deny = ALWAYS.find(([g]) => rx(g).test(rel));
  if (deny) return `Denied: ${deny[1]}.`;
  if (rx("reference/**").test(rel) && rel.toLowerCase() !== REFERENCE_OK.toLowerCase())
    return "Denied: reference/ holds what the style is built from (the user's references, sheets, stats); only reference/ANALYSIS.md is yours.";
  if (rx("audio/**").test(rel) && !AUDIO_ALLOWED.some((a) => a.toLowerCase() === rel.toLowerCase()))
    return "Denied: audio/ is the sample narration and its timing (the app's).";
  const allow = allowedFor(studio, studio.stage);
  if (allow.some((g) => rx(g).test(rel))) return null;
  return allow.length
    ? `Not at the ${studio.stage} stage: here the Style Studio lets you write only ${allow.join(", ")}. (${rel} belongs to another stage.)`
    : `Not at the ${studio.stage} stage: it writes no files (the app does this stage's work).`;
}
