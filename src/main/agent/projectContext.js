export function rulesText(projectId) {
  const g = q.all("SELECT * FROM rules WHERE scope='global' AND enabled=1 AND status='active' ORDER BY created_at");
  const p = projectId
    ? q.all("SELECT * FROM rules WHERE scope='project' AND project_id=? AND enabled=1 AND status='active' ORDER BY created_at", projectId)
    : [];
  return { global: g.map((r) => r.text), project: p.map((r) => r.text) };
}
export function writeStyleFiles(projectId) {
  const g = rulesText(null).global;
  fs.writeFileSync(
    ws.style(),
    `# Global style rules

Every Claude session in Videoxx follows these. Managed in the Memory page.

${g.map((r) => `- ${r}`).join("\n") || "(none yet)"}
`,
  );
  const ids = projectId ? [projectId] : q.all("SELECT id FROM projects").map((r) => r.id);
  for (const id of ids) {
    const p = q.get("SELECT * FROM projects WHERE id=?", id);
    if (!p || !fs.existsSync(p.path)) continue;
    const r = rulesText(id).project;
    fs.writeFileSync(
      path.join(p.path, "STYLE.md"),
      `# Project style rules

Rules for this video only. Managed in the Memory page.

${r.map((x) => `- ${x}`).join("\n") || "(none yet)"}
`,
    );
  }
}
