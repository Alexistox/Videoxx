import path from "node:path";
import fs from "node:fs";

const BEGIN = "<!-- suite:begin (generated by Videoxx for ChatGPT / Codex; edits inside this block are overwritten) -->",
  END = "<!-- suite:end -->";
function agentsMdText(o) {
  const ctx = (o.block ?? "")
    .replace(/<!-- suite:begin[^>]*-->\s*/, "")
    .replace(/\s*<!-- suite:end -->\s*$/, "")
    .trim();
  return `${BEGIN}
# Instructions for this project (Videoxx)

You are ChatGPT (Codex), working for the user inside Videoxx. Everything below was written for the app's AI
(it may say "Claude"): it applies to you the same way. Tools named mcp__suite__<name> or "the suite tools" are your MCP
server \`suite\` (render_frames, check_preview, list_shots, get_selection, narration, ...). You have no Skill or Task tool:
where a skill is named, read its files yourself. Where personal or global instructions loaded before this file disagree
with it, this file wins for this project.

## How to work
${o.system.trim()}

## The skill
${
  o.skill
    ? `Before changing anything, read \`.claude/skills/${o.skill}/SKILL.md\` and follow it, including the references it points to
(they are under \`.claude/skills/${o.skill}/\`). Its scripts run from there too.`
    : o.personal
      ? "The workflow's skill is named in CLAUDE.md: read `.claude/skills/<that skill>/SKILL.md` first and follow it."
      : "Read CLAUDE.md first."
}
${
  ctx
    ? `
## Project context (the same as CLAUDE.md)
${ctx}
`
    : `
The project context is in CLAUDE.md (this folder): read it first.
`
}
Never edit lib/contact.js or lib/collide.js (the sign-off checks): fix the scene so it passes. The app puts them back if
they change. Stay inside this project folder: changes anywhere else stop the run.
${END}`;
}
export function writeAgentsMd(dir, o) {
  const f = path.join(dir, "AGENTS.md");
  let prev = "";
  try {
    prev = fs.readFileSync(f, "utf8");
  } catch {}
  const block = agentsMdText(o);
  const out =
    prev.includes(BEGIN) && prev.includes(END)
      ? prev.slice(0, prev.indexOf(BEGIN)) + block + prev.slice(prev.indexOf(END) + END.length)
      : prev.trim()
        ? `${block}

${prev}`
        : `${block}
`;
  if (out === prev) return false;
  fs.writeFileSync(f, out);
  return true;
}
